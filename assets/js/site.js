/* ============================================================
   LearnInBits - site script
   ------------------------------------------------------------
   One script for every page. It:
     1. loads the data files (data/site.js, then the files that
        data/site.js lists in "dataFiles")
     2. builds the parts that repeat: header, footer, sidebars,
        roadmaps, lists, cards, tags and carousels
     3. makes every link to a different website open in a new tab

   Every page sets attributes on <body>:
     data-root    path from the page to the site root: "", "../" or "../../"
     data-page    home | courses | course | chapter | posts | post |
                  projects | project | topics | page
     data-course  course id            (course and chapter pages)
     data-id      chapter, post or project id
     data-kind    article | talk       (posts and post pages)
     data-section optional: which menu item to mark (for example "about")

   Places in a page where the script puts content have
   data-render="<what>". See PROJECT_CONTEXT.md for the full list.

   You do not edit this file to add content.
   ============================================================ */
