  /* ---------- 5. external links open in a new tab ---------- */
  function externalLinks(scope) {
    $all("a[href]", scope || document).forEach(function (a) {
      var h = a.getAttribute("href");
      if (!/^https?:\/\//i.test(h)) return;
      var host = "";
      try { host = new URL(h).host; } catch (e) { return; }
      if (host === location.host) return;
      a.setAttribute("target", "_blank");
      a.setAttribute("rel", "noopener noreferrer");
      if (!a.classList.contains("btn") && !a.classList.contains("card") && !a.closest(".site-footer") && !a.querySelector("img")) a.classList.add("ext");
      /* the tooltip shows the address of the link; screen readers still hear about the new tab */
      if (!a.title) a.title = h.replace(/^https?:\/\//i, "").replace(/\/$/, "");
      if (!a.querySelector(".sr-only")) a.insertAdjacentHTML("beforeend", '<span class="sr-only"> (opens in a new tab)</span>');
    });
  }

