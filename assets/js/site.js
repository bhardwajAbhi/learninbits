  /* ---------- code blocks ----------
     <pre class="code" data-lang="python|bash|text" data-file="src/x.py">...</pre>
     The script adds a header (file name or language), a copy button and
     colors for Python. Terminal blocks: data-lang="bash". Program output:
     data-lang="output". */
  var PY_KW = "False|None|True|and|as|assert|async|await|break|class|continue|def|del|elif|else|except|finally|for|from|global|if|import|in|is|lambda|nonlocal|not|or|pass|raise|return|try|while|with|yield";
  function highlightPython(src) {
    var re = new RegExp([
      "(#[^\\n]*)",                                                   // 1 comment
      "([rRbBfF]{0,2}(?:\"\"\"[\\s\\S]*?\"\"\"|'''[\\s\\S]*?'''|\"(?:\\\\.|[^\"\\\\\\n])*\"|'(?:\\\\.|[^'\\\\\\n])*'))", // 2 string
      "\\b(" + PY_KW + ")\\b",                                         // 3 keyword
      "\\b(\\d+(?:\\.\\d+)?)\\b",                                     // 4 number
      "(@\\w+)",                                                      // 5 decorator
      "\\b([A-Za-z_]\\w*)(?=\\s*\\()"                                   // 6 call
    ].join("|"), "g");
    var out = "", last = 0, m;
    while ((m = re.exec(src))) {
      out += esc(src.slice(last, m.index));
      var cls = m[1] ? "c" : m[2] ? "s" : m[3] ? "k" : m[4] ? "n" : m[5] ? "d" : "f";
      if (cls === "f" && /^[A-Z]/.test(m[0])) cls = "t";
      out += '<span class="tk-' + cls + '">' + esc(m[0]) + "</span>";
      last = re.lastIndex;
    }
    return out + esc(src.slice(last));
  }
  function highlightBash(src) {
    return src.split("\n").map(function (line) {
      if (/^\s*#/.test(line)) return '<span class="tk-c">' + esc(line) + "</span>";
      return esc(line).replace(/^(\s*)([\w.\/-]+)/, '$1<span class="tk-f">$2</span>');
    }).join("\n");
  }
  function initCode(scope) {
    $all("pre.code", scope).forEach(function (pre) {
      if (pre.getAttribute("data-ready")) return;
      pre.setAttribute("data-ready", "1");
      var lang = pre.getAttribute("data-lang") || "text";
      var codeEl = pre.querySelector("code") || pre;
      var raw = codeEl.textContent.replace(/^\n/, "").replace(/\s+$/, "");
      if (lang === "python") codeEl.innerHTML = highlightPython(raw);
      else if (lang === "bash") codeEl.innerHTML = highlightBash(raw);
      else codeEl.textContent = raw;
      var wrap = document.createElement("div");
      wrap.className = "codeblock lang-" + lang;
      var label = pre.getAttribute("data-file") || { python: "Python", bash: "Terminal", output: "Output", text: "Text" }[lang] || lang;
      var head = document.createElement("div");
      head.className = "code-head";
      head.innerHTML = '<span class="dots" aria-hidden="true"><i></i><i></i><i></i></span><span class="code-name">' + esc(label) + "</span>" +
        '<button type="button" class="copy-btn" aria-label="Copy the code">' + ICON.copy + "<span>Copy</span></button>";
      pre.parentNode.insertBefore(wrap, pre);
      wrap.appendChild(head);
      wrap.appendChild(pre);
      var btn = head.querySelector(".copy-btn");
      btn.addEventListener("click", function () {
        var text = raw.replace(/^\$ /gm, "");
        function done() { btn.classList.add("ok"); btn.querySelector("span").textContent = "Copied"; setTimeout(function () { btn.classList.remove("ok"); btn.querySelector("span").textContent = "Copy"; }, 1600); }
        try {
          if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(text).then(done, fallback);
          else fallback();
        } catch (e) { fallback(); }
        function fallback() {
          var ta = document.createElement("textarea");
          ta.value = text; ta.setAttribute("readonly", ""); ta.style.position = "fixed"; ta.style.opacity = "0";
          document.body.appendChild(ta); ta.select();
          try { document.execCommand("copy"); done(); } catch (e2) { /* copy not allowed */ }
          ta.remove();
        }
      });
    });
  }

  function buildToc(article, toc) {
    var heads = $all("h2", article);
    heads.forEach(function (h, i) {
      if (!h.id) h.id = h.textContent.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "s" + i;
    });
    if (heads.length < 2) { toc.remove(); return; }
    toc.innerHTML = '<div class="toc-title">On this page</div>' + heads.map(function (h) {
      return '<a href="#' + h.id + '">' + esc(h.getAttribute("data-toc") || h.textContent) + "</a>";
    }).join("");
    var links = $all("a", toc);
    function onScroll() {
      var y = window.scrollY + 120, active = 0;
      heads.forEach(function (h, i) { if (h.getBoundingClientRect().top + window.scrollY <= y) active = i; });
      links.forEach(function (a, i) { a.classList.toggle("active", i === active); });
    }
    window.addEventListener("scroll", onScroll, { passive: true });
    onScroll();
  }

